function icon(name) {
  const body = ICONS[name] || ICONS.info;
  return `<svg class="i" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

function rng(seed) {
  let s = seed >>> 0 || 1;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

function qrSvg(n = 25, seed = 7) {
  const r = rng(seed * 7919 + n);
  const m = Array.from({ length: n }, () => Array(n).fill(0));
  const reserved = Array.from({ length: n }, () => Array(n).fill(false));
  const finder = (x, y) => {
    for (let i = -1; i <= 7; i++) {
      for (let j = -1; j <= 7; j++) {
        const xx = x + j, yy = y + i;
        if (xx < 0 || yy < 0 || xx >= n || yy >= n) continue;
        reserved[yy][xx] = true;
        if (i < 0 || j < 0 || i > 6 || j > 6) { m[yy][xx] = 0; continue; }
        const edge = i === 0 || i === 6 || j === 0 || j === 6;
        const core = i >= 2 && i <= 4 && j >= 2 && j <= 4;
        m[yy][xx] = edge || core ? 1 : 0;
      }
    }
  };
  finder(0, 0); finder(n - 7, 0); finder(0, n - 7);
  for (let i = 8; i < n - 8; i++) { reserved[6][i] = true; reserved[i][6] = true; m[6][i] = i % 2 === 0 ? 1 : 0; m[i][6] = i % 2 === 0 ? 1 : 0; }
  for (let y = 0; y < n; y++) {
    for (let x = 0; x < n; x++) {
      if (reserved[y][x]) continue;
      m[y][x] = r() > 0.52 ? 1 : 0;
    }
  }
  let rects = '';
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) if (m[y][x]) rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  return `<svg viewBox="0 0 ${n} ${n}" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges" aria-label="二维码示意图"><rect width="${n}" height="${n}" fill="#fff"/><g fill="#0f172a">${rects}</g></svg>`;
}

